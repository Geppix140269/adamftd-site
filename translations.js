const RTL_LANGS = ['ar'];

/* Runtime: auto-tag elements by matching their English text, then swap.
   Avoids needing data-i18n attributes hand-added to 100+ elements. */
(function () {
  const norm = s => (s || '').replace(/\s+/g, ' ').trim();

  // Build reverse map: normalized English string -> key
  const enReverse = {};
  for (const k in TRANSLATIONS.en) {
    enReverse[norm(TRANSLATIONS.en[k])] = k;
  }

  let tagged = []; // { el, key, originalHTML }

  function tagElements() {
    const all = document.body.querySelectorAll('*');
    const candidates = [];
    all.forEach(el => {
      if (el.closest('.lang-switcher')) return;            // never translate switcher
      if (['SCRIPT', 'STYLE'].includes(el.tagName)) return;
      const key = enReverse[norm(el.textContent)];
      if (key) candidates.push(el);
    });
    // Keep only the deepest matching element (no descendant is also a candidate)
    const candSet = new Set(candidates);
    candidates.forEach(el => {
      const hasInnerCandidate = Array.from(el.querySelectorAll('*')).some(c => candSet.has(c));
      if (!hasInnerCandidate) {
        tagged.push({ el, key: enReverse[norm(el.textContent)], originalHTML: el.innerHTML });
      }
    });
  }

  function applyLanguage(lang) {
    const strings = TRANSLATIONS[lang];
    if (!strings) return;
    tagged.forEach(({ el, key, originalHTML }) => {
      if (lang === 'en') {
        el.innerHTML = originalHTML;            // restore original markup (em/strong/span styling)
      } else if (strings[key] !== undefined) {
        el.textContent = strings[key];
      }
    });
    const isRTL = RTL_LANGS.includes(lang);
    document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('.lang-btn').forEach(b =>
      b.classList.toggle('active', b.getAttribute('data-lang') === lang));
    try { localStorage.setItem('adamftd.lang', lang); } catch (e) {}
  }

  document.addEventListener('DOMContentLoaded', () => {
    tagElements();
    document.querySelectorAll('.lang-btn').forEach(b =>
      b.addEventListener('click', () => applyLanguage(b.getAttribute('data-lang'))));
    let saved = 'en';
    try { saved = localStorage.getItem('adamftd.lang') || 'en'; } catch (e) {}
    if (!TRANSLATIONS[saved]) saved = 'en';
    applyLanguage(saved);
  });
})();
